from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer


FIXTURES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fixtures")


class FakeMoonraker:
    def __init__(self, state="standby", box=None):
        self.uploads = []
        self.actions = []
        self.gcode = []
        self.box = None
        self.accept_filament = True
        if box:
            with open(os.path.join(FIXTURES, box)) as fh:
                self.box = json.load(fh)
        self.state = state
        outer = self

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def _json(self, obj):
                body = json.dumps(obj).encode()
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

            def do_GET(self):
                if self.path.startswith("/printer/info"):
                    return self._json({"result": {"state": "ready", "hostname": "qidi-q2"}})
                if self.path.startswith("/printer/objects/list"):
                    objs = (outer.box or {}).get("objects", ["print_stats", "extruder"])
                    return self._json({"result": {"objects": objs}})
                if self.path.startswith("/printer/objects/query"):
                    status = {"print_stats": {"state": outer.state}}
                    if outer.box:
                        status.update(outer.box["status"])
                    return self._json({"result": {"status": status}})
                if self.path.startswith("/server/files/config/officiall_filas_list.cfg") and outer.box:
                    body = outer.box["filas_list"].encode()
                    self.send_response(200)
                    self.send_header("Content-Length", str(len(body)))
                    self.end_headers()
                    self.wfile.write(body)
                    return
                self.send_error(404)

            def do_POST(self):
                n = int(self.headers["Content-Length"])
                body = self.rfile.read(n)
                if self.path.startswith("/server/files/upload"):
                    outer.uploads.append({"ctype": self.headers["Content-Type"], "body": body})
                    return self._json({"item": {"path": "x.gcode", "root": "gcodes"}, "print_started": True})
                if self.path.startswith("/printer/gcode/script"):
                    from urllib.parse import parse_qs, urlparse
                    script = parse_qs(urlparse(self.path).query)["script"][0]
                    outer.gcode.append(script)
                    import re as _re
                    m = _re.match(r"UPDATE_FILAMENT_INFORMATION SLOT=(\d+) COLOR='(\w+)' VENDOR='([^']*)' FILAMENT='([^']*)'", script)
                    if m and outer.box and outer.accept_filament:
                        n = int(m.group(1))
                        fi = outer.box["status"]["box_extras"]["boxes"][n // 4]["filament_info"][n % 4]
                        fi.update(color_rgb_str=["#" + m.group(2)], vendor_str=m.group(3), filament_str=m.group(4),
                                  filament_type=m.group(4).split()[0])
                    return self._json({"result": "ok"})
                if self.path.startswith("/printer/print/"):
                    outer.actions.append(self.path.rsplit("/", 1)[1])
                    return self._json({"result": "ok"})
                self.send_error(404)

        self.httpd = ThreadingHTTPServer(("127.0.0.1", 0), H)
        self.port = self.httpd.server_address[1]
        threading.Thread(target=self.httpd.serve_forever, daemon=True).start()

    def close(self):
        self.httpd.shutdown()


